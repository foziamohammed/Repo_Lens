import type { ScanResult, DocSection } from "@repolens/shared";

export class ApiTemplate {
  render(scan: ScanResult, generatedAt: string): DocSection {
    const { endpoints, meta } = scan;

    // Group endpoints by file/router
    const byFile: Record<string, typeof endpoints> = {};
    for (const ep of endpoints) {
      (byFile[ep.filePath] ??= []).push(ep);
    }

    const methodOrder = ["GET", "POST", "PUT", "PATCH", "DELETE"] as const;

    const sections = Object.entries(byFile)
      .map(([file, eps]) => {
        const sorted = [...eps].sort(
          (a, b) =>
            methodOrder.indexOf(a.method) - methodOrder.indexOf(b.method) ||
            a.path.localeCompare(b.path)
        );

        const epDocs = sorted
          .map((ep) => {
            const badge = this.methodBadge(ep.method);
            return [
              `### ${badge} \`${ep.path}\``,
              ``,
              `| | |`,
              `|---|---|`,
              `| **Method** | \`${ep.method}\` |`,
              `| **File** | \`${ep.filePath}\` |`,
              `| **Line** | ${ep.line} |`,
              ep.description ? `| **Description** | ${ep.description} |` : "",
            ]
              .filter((l) => l !== "")
              .join("\n");
          })
          .join("\n\n---\n\n");

        return `## \`${file}\`\n\n${epDocs}`;
      })
      .join("\n\n---\n\n");

    // Summary table
    const summaryTable =
      `| Method | Path | File | Line |\n` +
      `|--------|------|------|------|\n` +
      endpoints
        .map((e) => `| \`${e.method}\` | \`${e.path}\` | \`${e.filePath}\` | ${e.line} |`)
        .join("\n");

    // Method counts
    const methodCounts: Record<string, number> = {};
    for (const ep of endpoints) {
      methodCounts[ep.method] = (methodCounts[ep.method] ?? 0) + 1;
    }

    const methodSummary = Object.entries(methodCounts)
      .sort((a, b) => methodOrder.indexOf(a[0] as any) - methodOrder.indexOf(b[0] as any))
      .map(([m, c]) => `| \`${m}\` | ${c} |`)
      .join("\n");

    const content = `# API Reference

> Generated by RepoLens · ${generatedAt}  
> Project: \`${meta.name}\`

All endpoints listed here were extracted from the source code via static analysis.

## Summary

| Metric | |
|--------|--|
| Total endpoints | **${endpoints.length}** |
| Files with routes | **${Object.keys(byFile).length}** |

## Endpoints by Method

| Method | Count |
|--------|-------|
${methodSummary}

## All Endpoints

${summaryTable}

---

## Detailed Reference

${sections || "_No endpoints detected._"}
`;

    return {
      id: "api",
      title: "API Reference",
      content,
      sourceFiles: endpoints.map((e) => e.filePath),
      generatedAt,
    };
  }

  private methodBadge(method: string): string {
    const map: Record<string, string> = {
      GET: "🟢 GET",
      POST: "🔵 POST",
      PUT: "🟡 PUT",
      PATCH: "🟠 PATCH",
      DELETE: "🔴 DELETE",
    };
    return map[method] ?? method;
  }
}
