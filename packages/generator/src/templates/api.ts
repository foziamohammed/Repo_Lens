import type { ScanResult, DocSection } from "@repolens/shared";

export class ApiTemplate {
  render(scan: ScanResult, generatedAt: string): DocSection {
    const { endpoints } = scan;

    const endpointDocs = endpoints
      .map(
        (ep) =>
          `### \`${ep.method} ${ep.path}\`\n\n` +
          `- **File**: \`${ep.filePath}\` (line ${ep.line})\n` +
          (ep.description ? `- **Description**: ${ep.description}\n` : "")
      )
      .join("\n");

    const content = `# API Reference

> Generated by RepoLens on ${generatedAt}

This document lists all detected API endpoints extracted from the source code.

## Endpoints

${endpointDocs || "_No endpoints detected._"}
`;

    return {
      id: "api",
      title: "API Reference",
      content,
      sourceFiles: endpoints.map((e) => e.filePath),
      generatedAt,
    };
  }
}
