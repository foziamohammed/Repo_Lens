import type { ScanResult, DocSection } from "@repolens/shared";

export class ArchitectureTemplate {
  render(scan: ScanResult, generatedAt: string): DocSection {
    const { files, functions, classes, languages } = scan;

    // Group files by top-level directory
    const dirMap: Record<string, number> = {};
    for (const file of files) {
      const topDir = file.path.split("/")[0] ?? "(root)";
      dirMap[topDir] = (dirMap[topDir] ?? 0) + 1;
    }

    const dirList = Object.entries(dirMap)
      .sort((a, b) => b[1] - a[1])
      .map(([dir, count]) => `- \`${dir}/\` — ${count} file(s)`)
      .join("\n");

    const content = `# Architecture Overview

> Generated by RepoLens on ${generatedAt}

## Directory Structure

${dirList}

## Code Summary

| Metric | Count |
|--------|-------|
| Total files | ${files.length} |
| Functions detected | ${functions.length} |
| Classes detected | ${classes.length} |
| Languages | ${Object.keys(languages).length} |

## Languages

${Object.entries(languages)
  .sort((a, b) => b[1] - a[1])
  .map(([lang, count]) => `- **${lang}**: ${count} file(s)`)
  .join("\n")}
`;

    return {
      id: "architecture",
      title: "Architecture Overview",
      content,
      sourceFiles: [],
      generatedAt,
    };
  }
}
