import type { ScanResult, DocSection } from "@repolens/shared";

export class SetupTemplate {
  render(scan: ScanResult, generatedAt: string): DocSection {
    const { frameworks, dependencies } = scan;

    const hasNode = dependencies.some((d) => d.name === "node" || d.name === "npm");
    const hasYarn = dependencies.some((d) => d.name === "yarn");

    const installCmd = hasYarn ? "yarn install" : "npm install";
    const devCmd = hasYarn ? "yarn dev" : "npm run dev";

    const content = `# Setup Guide

> Generated by RepoLens on ${generatedAt}

## Prerequisites

- Node.js >= 20
- ${hasYarn ? "Yarn" : "npm"}

## Installation

\`\`\`bash
${installCmd}
\`\`\`

## Development

\`\`\`bash
${devCmd}
\`\`\`

## Detected Frameworks

${frameworks.length > 0 ? frameworks.map((f) => `- ${f}`).join("\n") : "- None detected"}
`;

    return {
      id: "setup",
      title: "Setup Guide",
      content,
      sourceFiles: [],
      generatedAt,
    };
  }
}
