import type { ScanResult, DocSection } from "@repolens/shared";

export class ReadmeTemplate {
  render(scan: ScanResult, generatedAt: string): DocSection {
    const { meta, languages, frameworks, dependencies, files } = scan;

    const topLanguages = Object.entries(languages)
      .sort((a, b) => b[1] - a[1])
      .slice(0, 5)
      .map(([lang, count]) => `- **${lang}**: ${count} file(s)`)
      .join("\n");

    const frameworkList =
      frameworks.length > 0
        ? frameworks.map((f) => `- ${f}`).join("\n")
        : "- None detected";

    const prodDeps = dependencies.filter((d) => !d.isDev).slice(0, 10);
    const depList =
      prodDeps.length > 0
        ? prodDeps.map((d) => `- \`${d.name}\` ${d.version}`).join("\n")
        : "- No dependencies found";

    const content = `# ${meta.name}

> Documentation generated by RepoLens on ${generatedAt}

## Overview

This project contains **${files.length} files** across the following languages:

${topLanguages}

## Frameworks & Libraries

${frameworkList}

## Dependencies

${depList}

## Getting Started

See the [Setup Guide](./setup.md) for installation and configuration instructions.

## Architecture

See the [Architecture Overview](./architecture.md) for a breakdown of project structure.
`;

    return {
      id: "readme",
      title: "README",
      content,
      sourceFiles: [],
      generatedAt,
    };
  }
}
