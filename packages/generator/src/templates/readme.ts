import type { ScanResult, DocSection } from "@repolens/shared";

export class ReadmeTemplate {
  render(scan: ScanResult, generatedAt: string): DocSection {
    const { meta, languages, frameworks, dependencies, files, functions, classes, endpoints } = scan;

    // Language breakdown with percentages
    const totalFiles = files.length;
    const topLanguages = Object.entries(languages)
      .sort((a, b) => b[1] - a[1])
      .map(([lang, count]) => {
        const pct = totalFiles > 0 ? ((count / totalFiles) * 100).toFixed(1) : "0";
        return `| ${lang} | ${count} | ${pct}% |`;
      })
      .join("\n");

    // Separate prod vs dev deps
    const prodDeps = dependencies.filter((d) => !d.isDev);
    const devDeps = dependencies.filter((d) => d.isDev);

    const prodDepList =
      prodDeps.length > 0
        ? prodDeps.map((d) => `| \`${d.name}\` | \`${d.version}\` |`).join("\n")
        : "| — | No production dependencies found |";

    const devDepList =
      devDeps.length > 0
        ? devDeps.map((d) => `| \`${d.name}\` | \`${d.version}\` |`).join("\n")
        : "| — | No dev dependencies found |";

    // Exported functions summary (top 20)
    const exportedFunctions = functions.filter((f) => f.isExported).slice(0, 20);
    const functionList =
      exportedFunctions.length > 0
        ? exportedFunctions
            .map((f) => {
              const params = f.params.length > 0 ? f.params.join(", ") : "";
              const async = f.isAsync ? "async " : "";
              return `| \`${async}${f.name}(${params})\` | \`${f.filePath}:${f.startLine}\` |`;
            })
            .join("\n")
        : "| — | No exported functions detected |";

    // Exported classes summary
    const exportedClasses = classes.filter((c) => c.isExported).slice(0, 15);
    const classList =
      exportedClasses.length > 0
        ? exportedClasses
            .map((c) => `| \`${c.name}\` | ${c.methods.map((m) => `\`${m}\``).join(", ") || "—"} | \`${c.filePath}:${c.startLine}\` |`)
            .join("\n")
        : "| — | — | No exported classes detected |";

    // Endpoint summary
    const endpointSection =
      endpoints.length > 0
        ? `## API Endpoints\n\n| Method | Path | File |\n|--------|------|------|\n` +
          endpoints
            .map((e) => `| \`${e.method}\` | \`${e.path}\` | \`${e.filePath}:${e.line}\` |`)
            .join("\n")
        : "";

    const frameworkBadges =
      frameworks.length > 0 ? frameworks.join(" · ") : "None detected";

    const content = `# ${meta.name}

> Auto-generated by RepoLens · ${generatedAt}

## Overview

| | |
|---|---|
| **Total files** | ${totalFiles} |
| **Languages** | ${Object.keys(languages).join(", ") || "—"} |
| **Frameworks** | ${frameworkBadges} |
| **Functions** | ${functions.length} (${exportedFunctions.length} exported) |
| **Classes** | ${classes.length} (${exportedClasses.length} exported) |
| **Dependencies** | ${prodDeps.length} production, ${devDeps.length} dev |
| **API Endpoints** | ${endpoints.length} |

## Languages

| Language | Files | Share |
|----------|-------|-------|
${topLanguages}

## Production Dependencies

| Package | Version |
|---------|---------|
${prodDepList}

## Dev Dependencies

| Package | Version |
|---------|---------|
${devDepList}

## Exported Functions

| Signature | Location |
|-----------|----------|
${functionList}

## Exported Classes

| Class | Methods | Location |
|-------|---------|----------|
${classList}

${endpointSection}

## Documentation

- [Setup Guide](./setup.md) — installation, environment, scripts
- [Architecture Overview](./architecture.md) — directory structure, module map
${endpoints.length > 0 ? "- [API Reference](./api.md) — all detected endpoints\n" : ""}
---
*Generated from ${totalFiles} files scanned at \`${meta.rootPath}\`*
`;

    return {
      id: "readme",
      title: "README",
      content,
      sourceFiles: [],
      generatedAt,
    };
  }
}
